    {
        var english = string.Equals(language, Locale.English, StringComparison.OrdinalIgnoreCase);
        Dictionary<string, object> resources = new(StringComparer.Ordinal);
        foreach (var (key, chinese, englishText) in Table)
        {
            resources[key] = english ? englishText : chinese;
        }

        return resources;
    }
